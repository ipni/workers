#!/usr/bin/env python3
"""Print the bootstrappers' DNS records as a Cloudflare-importable BIND file.

Generated from the inventory (IPs), bootstrap_instance_table in
group_vars/ipfs_nodes/main.yml (ports and hostname suffixes) and
host_vars/<box>/bootstrap.yml (PeerIDs, extra instances, legacy names), so the
records can never drift from what is deployed:

  ./scripts/bootstrap-dns.py > dns.txt                     # bootstrap.ipni.io
  ./scripts/bootstrap-dns.py --libp2p > dns-libp2p.txt     # bootstrap.libp2p.io

--libp2p prints the bootstrap.libp2p.io records for the legacy identities this
project now runs: each legacy name (_dnsaddr.<name>.bootstrap.libp2p.io) points
straight at our instance's addresses, and the shared _dnsaddr.bootstrap.libp2p.io
name lists every legacy identity, as it always has.

Boxes without a bootstrap_peer_id are skipped (and reported on stderr).
"""
import os
import sys

import yaml

ZONE = "ipni.io"
NAME = f"bootstrap.{ZONE}"
LEGACY_NAME = "bootstrap.libp2p.io"
TTL = 1   # "Auto" in Cloudflare, as in its own exports
TAG = "; cf_tags=cf-proxied:false"

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
hosts = yaml.safe_load(open(os.path.join(root, "inventory/hosts.yml")))["all"]["children"]["ipfs_nodes"]["hosts"]
# bootstrap_instances there is Jinja and cannot be evaluated here; the table it
# is built from is plain YAML.
table = yaml.safe_load(open(os.path.join(root, "group_vars/ipfs_nodes/main.yml")))["bootstrap_instance_table"]

instances = []   # (box, ip, host, peer_id, row, legacy name)
for box, vars_ in hosts.items():
    path = os.path.join(root, "host_vars", box, "bootstrap.yml")
    if not os.path.exists(path):
        print(f"skipping {box}: no {path}", file=sys.stderr)
        continue
    hv = yaml.safe_load(open(path))
    entries = [{"name": "bootstrap", "peer_id": hv["bootstrap_peer_id"],
                "legacy_name": hv.get("bootstrap_legacy_name")}] + hv.get("bootstrap_extra_instances", [])
    for e in entries:
        row = table[e["name"]]
        instances.append((box, vars_["ansible_host"], box + row["suffix"], e["peer_id"], row, e.get("legacy_name")))


def addresses(host, pid, row):
    for proto in (f"tcp/{row['swarm_port']}", f"udp/{row['swarm_port']}/quic-v1", f"tcp/{row['wss_port']}/wss"):
        yield f"/dns4/{host}.{NAME}/{proto}/p2p/{pid}"


def txt(name, value):
    return f'{name}.\t{TTL}\tIN\tTXT\t"dnsaddr={value}" {TAG}'


def ipni():
    out = [
        f";; Cloudflare DNS import for the {ZONE} bootstrap nodes (BIND format).",
        ";; GENERATED by scripts/bootstrap-dns.py - do not edit by hand.",
        ";; Import: DNS > Records > Import and Export > Import DNS records.",
        ";; Leave 'Proxy imported DNS records' UNCHECKED: raw libp2p TCP/UDP cannot",
        ";; be proxied. Every record also carries cf-proxied:false.",
        ";;",
        f";; Clients bootstrap with /dnsaddr/{NAME}/p2p/<PeerID>, one per bootstrapper:",
        *[f";;   {host}  {pid}" + (f"  (legacy {legacy}.{LEGACY_NAME})" if legacy else "")
          for _, _, host, pid, _, legacy in instances],
        "",
        ";; A records (DNS only)",
        *[f"{host}.{NAME}.\t{TTL}\tIN\tA\t{ip} {TAG}" for _, ip, host, _, _, _ in instances],
        "",
        ";; Shared name: one entry per bootstrap node",
        *[txt(f"_dnsaddr.{NAME}", f"/dnsaddr/{host}.{NAME}/p2p/{pid}") for _, _, host, pid, _, _ in instances],
    ]
    for _, _, host, pid, row, _ in instances:
        out += ["", f";; {host}: its addresses (TCP, QUIC, and WSS for browsers)"]
        out += [txt(f"_dnsaddr.{host}.{NAME}", a) for a in addresses(host, pid, row)]
    return out


def libp2p():
    legacy = [i for i in instances if i[5]]
    out = [
        f";; DNS records for {LEGACY_NAME} (BIND format), for the legacy bootstrap",
        f";; identities this project runs. GENERATED by scripts/bootstrap-dns.py --libp2p",
        ";; - do not edit by hand. Each legacy name points at our instance's direct",
        f";; /dns4/<host>.{NAME} addresses, which need the A records in dns.txt.",
        ";;",
        *[f";;   {name}.{LEGACY_NAME}  {pid}  -> {host}.{NAME}" for _, _, host, pid, _, name in legacy],
        "",
        ";; Shared name: one entry per legacy identity",
        *[txt(f"_dnsaddr.{LEGACY_NAME}", f"/dnsaddr/{name}.{LEGACY_NAME}/p2p/{pid}") for _, _, _, pid, _, name in legacy],
    ]
    for _, _, host, pid, row, name in legacy:
        out += ["", f";; {name}: {host}.{NAME} (TCP, QUIC, and WSS for browsers)"]
        out += [txt(f"_dnsaddr.{name}.{LEGACY_NAME}", a) for a in addresses(host, pid, row)]
    return out


if sys.argv[1:] not in ([], ["--libp2p"]):
    print(__doc__, file=sys.stderr)
    sys.exit(64)
print("\n".join(libp2p() if sys.argv[1:] == ["--libp2p"] else ipni()))
